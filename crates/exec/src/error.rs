//! 오류.

use chrono::{DateTime, Utc};
use pi_paper::{AccountKind, BrokerError};
use pi_store::{StoreError, TradeId, TradeState};
use thiserror::Error;

/// 이 모듈의 오류. 거부된 호출은 증권사에 주문을 내지 않는다(아래 각 줄에 예외를 적는다).
#[derive(Debug, Error)]
#[non_exhaustive]
pub enum Error {
    /// 다시 켠 뒤 저장소의 주문됨 매매와 증권사 주문을 아직 맞춰 보지 않았다(E16).
    /// [`crate::Executor::reconcile`]이 끝나기 전에는 새 주문(사기 · 팔기 · 다시 내기)을 받지 않는다.
    #[error("다시 켠 뒤 증권사와 맞춰 보기 전이라 새 주문을 받지 않는다")]
    NotReady,

    /// 계좌 종류가 증권사의 것과 다르다(E25). 템플릿의 계좌 종류나 매매의 계좌 종류 가운데
    /// 증권사와 다른 것이 `found`다. 매매는 그대로이고 주문을 내지 않는다.
    #[error("계좌 종류가 다르다: 증권사 {broker:?}, 받은 것 {found:?}")]
    AccountKindMismatch {
        /// 증권사의 계좌 종류.
        broker: AccountKind,
        /// 다른 쪽의 계좌 종류.
        found: AccountKind,
    },

    /// 점검 통과 표시의 내용이 매매와 맞지 않는다: 종목이 다르거나, 사는 길에 파는 표시가
    /// (또는 그 반대가) 왔거나, 다시 내는 파는 주문의 내용이 처음 것과 다르다.
    /// 매매는 그대로이고 주문을 내지 않는다.
    #[error("점검 통과 표시의 내용이 매매와 맞지 않는다")]
    PermitMismatch,

    /// 승인대기인 매매인데 승인 소비 결과가 없다. 매매는 그대로이고 주문을 내지 않는다.
    #[error("승인대기인 매매는 승인 소비 결과가 있어야 낸다")]
    ApprovalRequired,

    /// 승인 소비 결과(증표)가 그 매매의 승인이 아니다: 저장소의 승인 기록에 그 번호가 없거나,
    /// 승인됨 · 소비됨이 아니거나, 지문이 다르거나, 승인한 내용(매매 번호 · 종목 · 방향 · 수량 ·
    /// 값 · 계좌)이 이 매매 · 점검 통과 표시와 다르다. 매매는 그대로이고 주문을 내지 않는다.
    #[error("승인 증표가 이 매매의 승인이 아니다")]
    ApprovalMismatch,

    /// 답 없음 줄임 길([`crate::Executor::submit_reduced`])은 승인대기인 매매만 받는다. 지금 상태를
    /// 담는다. 매매는 그대로이고 주문을 내지 않는다.
    #[error("승인대기가 아닌 매매다: {0:?}")]
    NotAwaitingApproval(TradeState),

    /// 그 승인 번호가 이 매매의 "답 없음 · 줄여서 낼 것"이 아니다(E22): 기록이 없거나, 결과가 답 없음이
    /// 아니거나, 소비됐거나, 알림이 갔다는 기록이 없거나(P20), 신호 유효 시간이 지났거나, 처리 기록이
    /// 이미 있거나, 요청한 내용(매매 번호 · 종목 · 계좌 · 사기 · 호가 유형)이 이 매매 · 표시와 다르거나,
    /// 표시의 수량 · 금액이 요청한 수량 · 금액을 넘는다. 매매는 그대로이고 주문을 내지 않는다.
    #[error("그 승인 번호는 이 매매의 답 없는 사기(줄여서 낼 것)가 아니다")]
    UnansweredMismatch,

    /// 그 매매에 손절 · 청산이 다시 내기를 기다리고 있어(E30 · E34), 익절 · 팀장 팔기를 받지 않는다(8차).
    /// 기다리는 손절 · 청산(목적 · 횟수 · 시각 · 키)은 그대로이고 주문을 내지 않는다. 손절 · 청산은
    /// [`crate::Executor::retry_sell`]이나 새 손절 · 청산 `sell`로 낸다.
    #[error("손절 · 청산이 다시 내기를 기다리는 매매라 익절 · 팀장 팔기를 받지 않는다")]
    StopPending,

    /// 파는 수량이 그 매매의 남은(체결된, 아직 팔지 않은) 수량에서 그 매매에 이미 열려 있는 파는
    /// 주문의 남은 수량을 뺀 것보다 많다(8차). 손절 · 청산은 같은 종목의 열린 파는 주문을 취소한 뒤에
    /// 대조한다. 주문을 내지 않는다.
    #[error("파는 수량이 남은 수량 {remaining}보다 많다")]
    SellTooLarge {
        /// 그 매매의 남은 수량.
        remaining: rust_decimal::Decimal,
    },

    /// 파는 주문은 보유중인 매매에만 낸다. 지금 상태를 담는다.
    #[error("보유중이 아닌 매매다: {0:?}")]
    NotHolding(TradeState),

    /// 다시 낼 파는 주문이 없다.
    #[error("다시 낼 파는 주문이 없다: {0:?}")]
    NoPendingSell(TradeId),

    /// 다시 낼 때가 아직 아니다(물러서기 간격, E30). 증권사를 부르지 않고 횟수도 그대로다.
    #[error("다시 낼 때가 아직 아니다: {retry_at}")]
    RetryNotDue {
        /// 다시 낼 수 있는 가장 이른 시각.
        retry_at: DateTime<Utc>,
    },

    /// 증권사가 주문을 받지 않거나 응답하지 않았다(E13 · E30). 이상 감지 멈춤 요구다.
    /// 팀 상태를 바꾸는 것은 부르는 쪽이 한다.
    #[error("증권사 주문 실패(이상 감지 멈춤 요구): {0}")]
    AnomalyStop(BrokerError),

    /// 증권사가 그 밖의 이유로 주문을 거부했다(점검 표시가 맞지 않음(E33) 등).
    #[error("증권사가 주문을 거부했다: {0}")]
    Rejected(BrokerError),

    /// 저장소 오류. 주문됨으로 저장하지 못했으면 주문을 내지 않는다(persist-before-execute).
    #[error("저장소: {0}")]
    Store(#[from] StoreError),

    /// 저장소의 계좌 스냅샷을 되살릴 수 없다(V6). 처음 계좌로 열지 않는다.
    #[error("계좌 스냅샷을 되살릴 수 없다: {0}")]
    Snapshot(String),
}
