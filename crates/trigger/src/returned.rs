//! (8차, 백로그 U 3번 "본 것 기억 기록 시점") 상한으로 버린 자료 사건을 부르는 쪽에 돌려준다.
//!
//! 한 깨우기 상한 · 묶음 수 상한 · 장 밖 보관 상한으로 버린 사건은 수(`data_dropped`)로만 알리면 부르는 쪽이 그것을
//! "이미 넘긴 것"으로 기억해 다시 넘기지 않는다(그 뉴스는 다시 오지 않는다). 그래서 사건 그대로 돌려주고 중복 표에서
//! 뺀다 — 부르는 쪽은 기억에서 빼 다음 가져오기에서 다시 넘긴다. 그 사건이 들던 묶음이 깨우기로 나간 뒤에 돌려준다
//! (꽉 찬 묶음에 다시 넣어 곧바로 또 버리지 않게).
//!
//! 돌려주지 않는 것: 전체 정지로 버린 것(F4 7b2 — 의도된 버림, 그 묶음과 함께 상한으로 버린 것도), 구독을 꺼 버린
//! 것(7차 — 같은 사건으로 다시 깨우지 않는다), 실패한 깨우기에 실렸던 것(6차 — 다시 보내지 않는다).
//! 원본(Hermes webhook)에는 없다(원본은 묶음의 마지막 사건 하나만 보낸다).

use crate::engine::lock;
use crate::{DataChange, Trigger};

impl Trigger {
    /// 지난번 뒤로 상한으로 버려 돌려줄 자료 사건들(버린 순 — 묶음 안에서는 이른 순). 한 번만 준다. 돌려준
    /// 사건은 중복 표에서 빠졌으므로 다시 넣으면([`Trigger::push_data`]) 받는다. 쌓이는 수에는 끝이 있다(가장
    /// 오래된 것부터 잊는다).
    pub fn take_returned_data(&self) -> Vec<DataChange> {
        lock(&self.data).take_returned()
    }
}
