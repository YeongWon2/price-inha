//! 10차 10b(`docs/dev/modules/server.md` "10b 깨우기 · 자료")의 테스트: 모듈 차수가 만든 것을 실행 파일에 잇는다.
//!
//! 잠긴 테스트 파일을 고치지 않으려고 따로 둔 최상위 테스트 바이너리다. 서버는 임시 보관 폴더 ·
//! `127.0.0.1:0`으로 띄우고, 시세 · AI · 자료(DART · ECOS · FRED · 네이버 뉴스) · 웹 푸시는 시연용 가짜이거나
//! 로컬 가짜 서버뿐이다. 실제 증권사 · AI · 자료 서버를 부르지 않는다.
//!
//! - `carry`: 0번(10a 재검토에서 넘어온 것): 실패한 파는 주문 다시 내기 · 보유 종목의 시세 흐름 ·
//!   매수가 막힌 까닭(새 템플릿) · 자료 이상 알림 묶기.
//! - `wake`: 8번(트리거: 지켜보는 종목의 시세 조건 · 자료 변화로 깨우기 · 다시 켠 뒤 중복 · 네이버 하루 상한).
//! - `news`: 9번(논의 자료와 판단 기록의 뉴스 · 버린 기사 수 · FRED 미국 금리).
//! - `keys`: 10번(공급자 선언에서 만든 키 칸 목록 · 네이버 키 확인).
//! - 0번의 "개선안 답과 하루 마감의 승격 판정이 겹침"과 11번(시세 공급자 등록부)은 쓰지 않았다
//!   (겹침을 정해진 차례로 만드는 공개 길이 없다 · 밖에서 보이는 차이가 없어 기존 시세 시험으로 충분하다).
//!
//! 10b 보강(검토 되돌림)에서 더한 것:
//! - `dart`: 1번(DART 하루 상한 · 장 시간 안에서만 주기 가져오기, 네이버도).
//! - `screens`: 2번(두 화면이 새 칸 목록 경로를 읽고 옛 자료 키 칸이 없다).
//! - `macro_wake`: 3번(재무 · 거시 값 바뀜으로 깨우기 · scout가 고른 종목 논의 · `(pass)`).
//! - `backoff`: 5번(막힌 다시 내기의 물러서기 · 손절을 다시 내지 못한다는 알림).
//! - `source`: 6번(깨우기 글의 출처 · 바깥 글 표시).
//! - `stop_backoff`: 보강 2 1번(장 밖에서 막힌 손절이 밤을 넘겨 다음 장 시작 몇 초 안에 팔린다).
//! - 4번(템플릿 구독 트리거)은 10b 보강 때 쓰지 않았다(스윙 프리셋에 뉴스 구독이 없어 `wake`와 부딪혔다).
//!
