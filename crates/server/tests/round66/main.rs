//! 백로그 T(결정 29 · 30의 남은 것) 시험. 번호는 round59 · round60이 쓴 제안 번호(V98~V104 · V59)를 잇는다.
//!
//! - `scaffold`: 발판이 지금 구현에서 서는가(논의로 사서 보유중 → 익절로 팔림 → 하루 마감).
//! - `to_rules`: 1층으로 가는 지침 후보 가운데 어느 규칙 값을 어떻게 바꾸자는 것인지 읽히는 것만 개선안 · 승인 요청이
//!   되고(`to_rules` 이벤트가 그 개선안을 가리킨다), 읽히지 않으면 이벤트만 남는다.
//! - `score`: 지침이 든 논의 → 사기 → 익절(손절)로 팔림 → 하루 정리에서 그 지침의 익절(손절)이 오른다.
//! - `error_use`: 논의가 오류로 끝나면 그 매매의 쓰임이 장부에서 지워진다.
//! - `days`: 하루 정리를 돌지 않은 거래일도 서버가 남긴 하루 시작 기록으로 세어 30일 미사용 · 5일 막힘을 본다.
//! - `messenger_gather`: 메신저(가짜 텔레그램)로 팀 방에 멘션 글을 보내면 멘션된 담당 모두가 곧바로 오는 중이 된다.
//!
//! 서버는 임시 보관 폴더 · `127.0.0.1:0`로 띄운다. 메신저 시험만 시연이 아닌 조립이고(시연이면 메신저 루프가 돌지
//! 않는다), 나머지는 시연 모드(가짜 AI · 가짜 시세 · 모의계좌)다. 바깥 주소 자리는 모두 로컬 가짜 서버다.

