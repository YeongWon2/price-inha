//! 팀 지침(기능 L · 결정 30 · R7 · R8 확장) 시험. 번호 V99~V104는 이 차수에서 설계서에 더할 제안 번호다.
//!
//! - `bench`: 발판이 지금 구현에서 서는가(서버가 뜨고 · 팔린 매매에 복기를 넣고 · 하루 마감을 부를 수 있다).
//! - `ledger`: 시연 기록(같은 실수 세 번)으로 지침이 올라 장부 파일(0600)에 남고 이벤트가 생기며, 다음 논의의 판단
//!   글에 "팀 지침" 블록이 든다. 1층을 건드리는 되풀이는 지침이 되지 못한다. 지침이 없으면 블록이 없다.
//! - `api`: `GET /api/guidelines`(원격 세션도 읽는다) · `POST /api/guidelines/{id}/retire`(이 컴퓨터만, 원격 403).
//! - `wrap`: 하루 정리 회고가 성적이 나쁜 지침을 내린다.
//!
//! 서버는 임시 보관 폴더 · `127.0.0.1:0` · 시연 모드(가짜 AI · 가짜 시세 · 모의계좌)로 띄운다. 바깥 주소 자리는
//! 모두 로컬 가짜 서버다. 화면 동작의 시험은 vitest(`tests/web/rules-guidelines.test.ts`)에 있다.

