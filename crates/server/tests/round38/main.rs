//! server 37차 시험: `price-inha setup [구역]` 터미널 마법사와 `open` 명령(결정 24 · D4 · D1).
//!
//! 마법사는 실행 파일을 띄워 **표준 입력으로 답을 흘려 넣는 숨은 길(`--stdin-answers`)**로 본다(진짜 터미널
//! 없이). 답 형식과 질문 차례는 `price_inha::setup`(뼈대 `src/cli/setup.rs`)의 모듈 문서가 계약이다.
//!
//! - `parse`: 하위 명령 읽기(`setup [구역] [--stdin-answers] [--dry-run]` · `open [화면] [--print]`).
//! - `guard`: 비대화형이면 종료 코드 2와 안내 · 마법사 코드가 다른 프로그램의 토큰 파일을 열지 않는다(코드 검사).
//! - `ai`: AI 연결 구역 — 로그인된 CLI · 로그인 안 됨(안내 → Enter → 다시 확인) · API 키(출력 · 기록 어디에도
//!   키 글자 없음) · 틀린 키는 서버의 거절 글 뒤 다시 묻기 · 시도 제한이면 멈춤 · 건너뛰기 · 과금 경고.
//! - `keys`: 증권 키 · 종목이 도는 서버의 설정 경로로 저장된다 · 빈 입력은 건너뛰기 · 업종표 안내.
//! - `flow`: 구역을 차례로 지나 끝 요약 · 이미 설정된 홈에서 "있음"과 구역 고르기 · 서비스 구역(dry-run).
//! - `noserver`: 도는 서버가 없으면 띄울지 묻고, 띄운 서버로 저장한 뒤 끈다 · 아니오면 저장하지 않는다.
//! - `open`: 도는 서버가 있으면 화면 주소(`--print`) · 없으면 종료 코드 1 · 모르는 화면은 2.
//!
//! 실제 AI · 증권사 · 브라우저 · 서비스 관리자를 부르지 않는다. 가짜 `claude`는 임시 폴더의 셸 스크립트,
//! 바깥 서버는 로컬 가짜 서버(wiremock)뿐이다. 사용자 홈 · 보관 폴더는 임시 폴더이고 시험이 지운다.

